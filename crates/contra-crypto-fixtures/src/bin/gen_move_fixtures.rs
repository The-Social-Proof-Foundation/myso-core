use contra_crypto_fixtures::{
    SINGLE_AMOUNT_DST, TWO_AMOUNT_DST, assert_wire_proof_valid, batch_range_proof_wire,
    format_move_vector_u8, pedersen_commitment_bytes,
};
use rand::SeedableRng;
use rand::rngs::StdRng;
use std::fs;
use std::path::PathBuf;

fn main() {
    let mut rng = StdRng::seed_from_u64(42);

    let single_values = [1234u64, 0, 0, 0];
    let single_blindings = [7777u64, 0, 0, 0];
    let single_proof =
        batch_range_proof_wire(&single_values, &single_blindings, 16, SINGLE_AMOUNT_DST, &mut rng);
    assert_wire_proof_valid(
        &single_proof,
        &single_values,
        &single_blindings,
        16,
        SINGLE_AMOUNT_DST,
    );

    let two_values = [50u64, 0, 0, 0, 30u64, 0, 0, 0];
    let two_blindings = [10097u64, 0, 0, 0, 76520u64, 0, 0, 0];
    let two_proof =
        batch_range_proof_wire(&two_values, &two_blindings, 16, TWO_AMOUNT_DST, &mut rng);
    assert_wire_proof_valid(&two_proof, &two_values, &two_blindings, 16, TWO_AMOUNT_DST);

    let mut tampered = single_proof.clone();
    tampered[10] ^= 0xff;

    let single_commitments: Vec<String> = single_values
        .iter()
        .zip(&single_blindings)
        .map(|(&v, &b)| format_move_vector_u8(&pedersen_commitment_bytes(v, b)))
        .collect();

    let two_commitments: Vec<String> = two_values
        .iter()
        .zip(&two_blindings)
        .map(|(&v, &b)| format_move_vector_u8(&pedersen_commitment_bytes(v, b)))
        .collect();

    let content = format!(
        r#"// Copyright (c) The Social Proof Foundation, LLC.
// SPDX-License-Identifier: Apache-2.0
//
// @generated by `cargo run -p contra-crypto-fixtures --bin gen_move_fixtures`

#[test_only]
module contra::bulletproof_fixtures;

use contra::encrypted_amount;

/// 21-byte DST for single-amount well-formed proof tests.
public fun single_amount_dst(): vector<u8> {{
    b"dst-match-21-byte-tag"
}}

/// 21-byte DST for two-amount batch proof tests.
public fun two_amount_dst(): vector<u8> {{
    b"two-amt-dst-21-bytes!!"
}}

/// Wrong DST for negative tests.
public fun wrong_dst(): vector<u8> {{
    b"wrong-dst-21-byte-tag!!"
}}

public fun single_amount_range_proof(): vector<u8> {{
    {single_proof}
}}

public fun two_amount_range_proof(): vector<u8> {{
    {two_proof}
}}

public fun tampered_single_amount_range_proof(): vector<u8> {{
    {tampered}
}}

/// Pedersen commitment bytes aligned with `single_amount_range_proof` limb order.
public fun single_amount_commitments(): vector<vector<u8>> {{
    vector[
        {c0},
        {c1},
        {c2},
        {c3},
    ]
}}

/// Pedersen commitment bytes for the two-amount batch proof (8 limbs).
public fun two_amount_commitments(): vector<vector<u8>> {{
    vector[
        {t0}, {t1}, {t2}, {t3}, {t4}, {t5}, {t6}, {t7},
    ]
}}

public fun two_amount_pedersen_aligned(): vector<encrypted_amount::EncryptedAmount> {{
    let c = two_amount_commitments();
    vector[
        encrypted_amount::new_encrypted_amount_from_ciphertexts_for_testing(
            c[0], c[1], c[2], c[3],
        ),
        encrypted_amount::new_encrypted_amount_from_ciphertexts_for_testing(
            c[4], c[5], c[6], c[7],
        ),
    ]
}}

/// Build an `EncryptedAmount` whose limb ciphertexts match `single_amount_range_proof`.
public fun single_amount_pedersen_aligned(): encrypted_amount::EncryptedAmount {{
    let c = single_amount_commitments();
    encrypted_amount::new_encrypted_amount_from_ciphertexts_for_testing(
        c[0],
        c[1],
        c[2],
        c[3],
    )
}}
"#,
        single_proof = format_move_vector_u8(&single_proof),
        two_proof = format_move_vector_u8(&two_proof),
        tampered = format_move_vector_u8(&tampered),
        c0 = single_commitments[0],
        c1 = single_commitments[1],
        c2 = single_commitments[2],
        c3 = single_commitments[3],
        t0 = two_commitments[0],
        t1 = two_commitments[1],
        t2 = two_commitments[2],
        t3 = two_commitments[3],
        t4 = two_commitments[4],
        t5 = two_commitments[5],
        t6 = two_commitments[6],
        t7 = two_commitments[7],
    );

    let out = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../myso-framework/packages/contra/tests/bulletproof_fixtures.move");
    fs::write(&out, content).expect("write bulletproof_fixtures.move");
    println!("Wrote {}", out.display());
}
